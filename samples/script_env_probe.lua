-- probe: what does the VM see for script/env/debug.info?
local s = script
print("type(script)=", type(s))
print("typeof(script)=", typeof(s))
print("script.Name=", s.Name)
print("script.ClassName=", s.ClassName)
print("script:GetFullName()=", s:GetFullName())
print("debug.info(1,'s')=", debug.info(1, "s"))
print("debug.info(1,'l')=", debug.info(1, "l"))
print("debug.info(script_fn)=", debug.info(function() end, "s"))
local env = getfenv()
print("rawget(env,'script') type=", type(rawget(env, "script")))
print("env has metatable=", type(getmetatable(env)))
print("pcall(assert)=", pcall(assert, false))
print("debug.info(2,'s')=", debug.info(2, "s"))
print("debug.traceback()=", debug.traceback())
print("tostring(script)=", tostring(s))
print("script:IsA('LocalScript')=", s:IsA("LocalScript"))
print("script.Parent type=", type(s.Parent))
